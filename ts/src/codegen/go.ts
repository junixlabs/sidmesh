import { baseType, deref, isNullable, isRecord } from "../schema.js";
import type { Contract, JsonSchema } from "../types.js";
import { goName, pascal, typePrefix } from "./names.js";

/** Collects named struct declarations while types are being resolved. */
class GoFile {
  private readonly decls: string[] = [];
  private readonly names = new Set<string>();

  uniqueName(name: string): string {
    let candidate = name;
    for (let i = 2; this.names.has(candidate); i++) {
      candidate = `${name}${i}`;
    }
    this.names.add(candidate);
    return candidate;
  }

  /** Declare a named type for a top-level schema (Input, Config, outputs). */
  declare(name: string, schema: JsonSchema): void {
    const typeName = this.uniqueName(name);
    const node = deref(schema, schema);
    if (node && baseType(node) === "object") {
      this.decls.push(`type ${typeName} ${this.struct(typeName, node, schema)}`);
    } else {
      this.decls.push(`type ${typeName} ${this.typeOf(typeName, schema, schema)}`);
    }
  }

  private struct(owner: string, node: JsonSchema, root: JsonSchema): string {
    const props = isRecord(node.properties) ? (node.properties as Record<string, JsonSchema>) : {};
    const required = Array.isArray(node.required) ? (node.required as string[]) : [];
    const entries = Object.entries(props);
    if (entries.length === 0) {
      return "struct{}";
    }
    const fields = entries.map(([key, prop]) => {
      const field = goName(key);
      const resolved = deref(prop, root) ?? {};
      const isRequired = required.includes(key);
      let type = this.typeOf(owner + field, prop, root);
      const pointerable = !type.startsWith("[]") && !type.startsWith("map[") && type !== "any";
      if (pointerable && (!isRequired || isNullable(resolved))) {
        type = `*${type}`;
      }
      const tag = isRequired ? key : `${key},omitempty`;
      return { field, type, tag: `\`json:"${tag}"\`` };
    });
    // Align name and type columns the way gofmt does, so the output is gofmt-clean as written.
    const fieldWidth = Math.max(...fields.map((f) => f.field.length));
    const typeWidth = Math.max(...fields.map((f) => f.type.length));
    const lines = fields.map((f) => `\t${f.field.padEnd(fieldWidth)} ${f.type.padEnd(typeWidth)} ${f.tag}`);
    return `struct {\n${lines.join("\n")}\n}`;
  }

  private typeOf(hint: string, schema: JsonSchema, root: JsonSchema): string {
    const node = deref(schema, root);
    if (!node) {
      return "any";
    }
    const constType = node.const !== undefined ? typeof node.const : undefined;
    const base = baseType(node) ?? (constType === "string" ? "string" : undefined);
    switch (base) {
      case "string":
        return "string";
      case "integer":
        return "int64";
      case "number":
        return "float64";
      case "boolean":
        return "bool";
      case "array":
        return `[]${isRecord(node.items) ? this.typeOf(hint + "Item", node.items as JsonSchema, root) : "any"}`;
      case "object": {
        const name = this.uniqueName(hint);
        this.decls.push(`type ${name} ${this.struct(name, node, root)}`);
        return name;
      }
      default:
        return "any";
    }
  }

  render(pkg: string): string {
    return [
      "// Code generated by sidmesh codegen. DO NOT EDIT.",
      "",
      `package ${pkg}`,
      "",
      this.decls.join("\n\n"),
      "",
    ].join("\n");
  }
}

/** contracts_gen.go for one Go node; package name is the node id. */
export function generateGo(nodeId: string, contracts: Contract[]): string {
  const file = new GoFile();
  for (const contract of contracts) {
    const prefix = typePrefix(contract.capability, contract.version);
    file.declare(`${prefix}Input`, contract.input);
    file.declare(`${prefix}Config`, contract.config ?? { type: "object", properties: {} });
    for (const [name, outcome] of Object.entries(contract.outcomes)) {
      file.declare(`${prefix}${pascal(name)}Output`, outcome.output);
    }
  }
  return file.render(nodeId);
}
