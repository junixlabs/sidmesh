import { baseType, deref, isNullable, isRecord } from "../schema.js";
import type { Contract, JsonSchema } from "../types.js";
import { handlerKey, pascal, typePrefix } from "./names.js";

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function indent(level: number): string {
  return "  ".repeat(level);
}

function tsType(schema: JsonSchema, root: JsonSchema, level: number, depth = 0): string {
  const node = deref(schema, root);
  if (!node || depth > 32) {
    return "unknown";
  }
  let type: string;
  if (node.const !== undefined) {
    type = JSON.stringify(node.const);
  } else if (Array.isArray(node.enum)) {
    type = node.enum.map((v) => JSON.stringify(v)).join(" | ");
  } else {
    switch (baseType(node)) {
      case "string":
        type = "string";
        break;
      case "integer":
      case "number":
        type = "number";
        break;
      case "boolean":
        type = "boolean";
        break;
      case "array": {
        const item = isRecord(node.items) ? tsType(node.items as JsonSchema, root, level, depth + 1) : "unknown";
        type = item.includes("|") || item.includes("{") ? `Array<${item}>` : `${item}[]`;
        break;
      }
      case "object":
        type = tsObject(node, root, level, depth);
        break;
      default:
        type = "unknown";
    }
  }
  return isNullable(node) ? `${type} | null` : type;
}

function tsObject(node: JsonSchema, root: JsonSchema, level: number, depth: number): string {
  const props = isRecord(node.properties) ? (node.properties as Record<string, JsonSchema>) : {};
  const required = Array.isArray(node.required) ? (node.required as string[]) : [];
  const entries = Object.entries(props);
  if (entries.length === 0) {
    return "Record<string, never>";
  }
  const lines = entries.map(([key, prop]) => {
    const name = IDENT.test(key) ? key : JSON.stringify(key);
    const optional = required.includes(key) ? "" : "?";
    return `${indent(level + 1)}${name}${optional}: ${tsType(prop, root, level + 1, depth + 1)};`;
  });
  return `{\n${lines.join("\n")}\n${indent(level)}}`;
}

/** contracts.gen.ts for one TS node. */
export function generateTs(contracts: Contract[]): string {
  const out: string[] = [
    "// Code generated by sidmesh codegen. DO NOT EDIT.",
    "",
    'import type { Meta } from "@sidmesh/core";',
    "",
  ];
  const handlerEntries: string[] = [];
  for (const contract of contracts) {
    const prefix = typePrefix(contract.capability, contract.version);
    const config = contract.config ?? { type: "object", properties: {} };
    out.push(`/** ${contract.capability} v${contract.version}: ${contract.summary} */`);
    out.push(`export type ${prefix}Input = ${tsType(contract.input, contract.input, 0)};`, "");
    out.push(`export type ${prefix}Config = ${tsType(config, config, 0)};`, "");
    const results: string[] = [];
    for (const [name, outcome] of Object.entries(contract.outcomes)) {
      const outputName = `${prefix}${pascal(name)}Output`;
      out.push(`export type ${outputName} = ${tsType(outcome.output, outcome.output, 0)};`, "");
      results.push(`  | { outcome: ${JSON.stringify(name)}; output: ${outputName} }`);
    }
    out.push(`export type ${prefix}Result =\n${results.join("\n")};`, "");
    out.push(
      `export type ${prefix}Handler = (`,
      `  input: ${prefix}Input,`,
      `  config: ${prefix}Config,`,
      "  meta: Meta,",
      `) => Promise<${prefix}Result>;`,
      "",
    );
    handlerEntries.push(`  ${JSON.stringify(handlerKey(contract.capability, contract.version))}: ${prefix}Handler;`);
  }
  // A type alias, not an interface: only an alias is assignable to NodeHandlers's index signature.
  out.push("/** Shape of the handlers object this node exports. */");
  out.push(`export type Handlers = {\n${handlerEntries.join("\n")}\n};`, "");
  return out.join("\n");
}
